-- Medical Center API domain schema reference for PostgreSQL.
-- Source of truth: Django migrations, not this reference file.

CREATE TABLE specialists_specialty (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(120) NOT NULL UNIQUE,
    description text NOT NULL,
    is_active boolean NOT NULL DEFAULT TRUE,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL
);

CREATE TABLE specialists_specialist (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name varchar(100) NOT NULL,
    last_name varchar(100) NOT NULL,
    license_number varchar(50) NOT NULL UNIQUE,
    email varchar(254) NOT NULL UNIQUE,
    phone varchar(30) NOT NULL,
    is_active boolean NOT NULL DEFAULT TRUE,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    specialty_id bigint NOT NULL REFERENCES specialists_specialty(id)
);

CREATE TABLE patients_patient (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name varchar(100) NOT NULL,
    last_name varchar(100) NOT NULL,
    document_number varchar(50) NOT NULL UNIQUE,
    date_of_birth date NOT NULL,
    email varchar(254) NOT NULL,
    phone varchar(30) NOT NULL,
    is_active boolean NOT NULL DEFAULT TRUE,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL
);

CREATE TABLE facilities_office (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL UNIQUE,
    floor varchar(30) NOT NULL,
    description text NOT NULL,
    is_active boolean NOT NULL DEFAULT TRUE,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL
);

CREATE TABLE scheduling_workingschedule (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    weekday smallint NOT NULL,
    start_time time NOT NULL,
    end_time time NOT NULL,
    is_active boolean NOT NULL DEFAULT TRUE,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    specialist_id bigint NOT NULL REFERENCES specialists_specialist(id),
    CONSTRAINT unique_specialist_schedule UNIQUE (specialist_id, weekday, start_time, end_time)
);

CREATE TABLE appointments_appointment (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    start_at timestamptz NOT NULL,
    end_at timestamptz NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'scheduled',
    reason varchar(255) NOT NULL,
    notes text NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    office_id bigint NOT NULL REFERENCES facilities_office(id),
    patient_id bigint NOT NULL REFERENCES patients_patient(id),
    specialist_id bigint NOT NULL REFERENCES specialists_specialist(id)
);

